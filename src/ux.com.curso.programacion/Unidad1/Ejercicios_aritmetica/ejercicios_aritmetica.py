# ejemplo de uso de operadores de aritmetica en python
def operaciones_aritmeticas():
    #suma 
    suma = 5 + 3
    print(f"suma: {suma}")
    #resta
    resta = 10 - 4
    print(f"resta: {resta}")

    #multiplicacion
    multiplicacion = 6 * 7
    print(f"multiplicacion: {multiplicacion}")

    # division aritmetica
    division = 10 // 3
    print(f"division: {division}")
    
    # modulo
    modulo = 10 % 3
    print(f"modulo: {modulo}")
    
    # potenciacion
    potenciacion = 2 ** 3
    print(f"potenciacion: {potenciacion}")

def main():
    operaciones_aritmeticas()

if __name__ == "__main__":
    main()





